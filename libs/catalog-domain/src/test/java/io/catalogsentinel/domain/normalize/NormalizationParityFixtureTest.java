package io.catalogsentinel.domain.normalize;

import io.catalogsentinel.domain.listing.Gtin;
import io.catalogsentinel.domain.listing.ListingContent;
import io.catalogsentinel.domain.testsupport.RepoFiles;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Keeps {@code tests/fixtures/normalization-parity-golden.tsv} in sync with the Java normalizers. The file holds
 * the Java output for every field of both golden catalogs (plus each listing's content hash) and is consumed by
 * the PySpark batch tests, so the Python port of the text rules is checked against real Java output on ~200
 * realistic listings, not only against hand-written cases.
 *
 * <p>If a deliberate normalization change makes this test fail, regenerate the fixture with
 * {@code -Dcatalogsentinel.regenerateFixtures=true}, bump {@link ProductNormalizer#VERSION}, and port the change
 * to {@code jobs/catalog-batch/catalog_batch/normalize.py}.
 */
class NormalizationParityFixtureTest {

    private static final String FIXTURE = "tests/fixtures/normalization-parity-golden.tsv";
    private static final List<String> SOURCES = List.of("tests/golden-matching/golden-listings.tsv",
            "tests/golden-matching/golden-holdout.tsv");

    @Test
    void parityFixtureMatchesTheJavaNormalizers() throws IOException {
        String expected = render();
        Path path = RepoFiles.locate("tests/fixtures").resolve("normalization-parity-golden.tsv");
        if (Boolean.getBoolean("catalogsentinel.regenerateFixtures") || !Files.exists(path)) {
            Files.writeString(path, expected, StandardCharsets.UTF_8);
        }
        assertThat(Files.readString(path, StandardCharsets.UTF_8))
                .as("%s is stale; regenerate with -Dcatalogsentinel.regenerateFixtures=true", FIXTURE)
                .isEqualTo(expected);
    }

    static String render() {
        StringBuilder sb = new StringBuilder();
        sb.append("# GENERATED by NormalizationParityFixtureTest from the golden catalogs; do not edit by hand.\n")
                .append("# Columns: kind<TAB>input<TAB>expected (\"<null>\" means null). kind content_hash: input is the\n")
                .append("# listing id in the golden files, expected is ListingContent.contentHash().\n")
                .append("# normalizer=").append(ProductNormalizer.VERSION).append('\n');
        for (String source : SOURCES) {
            List<String[]> rows = RepoFiles.readTsv(source);
            for (String[] c : rows.subList(1, rows.size())) { // skip header
                String title = c[4];
                String brand = blankToNull(c[5]);
                String model = blankToNull(c[6]);
                String category = blankToNull(c[7]);
                String gtin = blankToNull(c[8]);
                row(sb, "title", title, TextNormalizer.normalizeTitle(title));
                if (brand != null) {
                    row(sb, "brand", brand, BrandNormalizer.normalize(brand));
                }
                if (model != null) {
                    row(sb, "model", model, ModelNormalizer.normalize(model));
                }
                if (category != null) {
                    row(sb, "category", category, CategoryNormalizer.normalize(category));
                }
                if (gtin != null) {
                    row(sb, "gtin", gtin, Gtin.parse(gtin).map(Gtin::value).orElse(null));
                }
                ListingContent content = ListingContent.of(title, brand, model, category, gtin, attributes(c[9]));
                row(sb, "content_hash", c[0], content.contentHash());
            }
        }
        return sb.toString();
    }

    private static void row(StringBuilder sb, String kind, String input, String expected) {
        sb.append(kind).append('\t').append(input).append('\t').append(expected == null ? "<null>" : expected).append('\n');
    }

    private static String blankToNull(String s) {
        return s == null || s.isBlank() ? null : s;
    }

    /** Same encoding as the golden files: {@code k=v;k2=v2}. */
    static Map<String, String> attributes(String cell) {
        Map<String, String> m = new LinkedHashMap<>();
        if (cell == null || cell.isBlank()) {
            return m;
        }
        List<String> pairs = new ArrayList<>(List.of(cell.split(";")));
        for (String pair : pairs) {
            int eq = pair.indexOf('=');
            if (eq > 0) {
                m.put(pair.substring(0, eq).strip(), pair.substring(eq + 1).strip());
            }
        }
        return m;
    }
}
